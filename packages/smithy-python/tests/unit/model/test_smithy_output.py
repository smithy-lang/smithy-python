"""Load a JSON AST produced by the Smithy CLI.

The other tests use hand-written ASTs. ``fixtures/mini.json`` was generated by
Smithy 1.73.0, so it guards against those tests assuming a serialization that
Smithy does not actually produce. It may be edited directly.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from smithy_python.model import (
    EnumShape,
    Model,
    ShapeId,
    StructureShape,
    load_model,
)

MINI = Path(__file__).parent / "fixtures" / "mini.json"


@pytest.fixture(scope="module")
def model() -> Model:
    return load_model(MINI.read_bytes())


def _id(name: str) -> ShapeId:
    return ShapeId("example.mini", name)


def test_services_and_prelude(model: Model) -> None:
    assert [str(s.id) for s in model.services()] == ["example.mini#Mini"]
    assert not any(model.is_prelude(s) for s in model.iter_shapes())
    assert list(model.metadata) == ["alpha", "suppressions", "zeta"]


def test_mixins_and_applies(model: Model) -> None:
    thing = model.expect_shape(_id("Thing"), StructureShape)
    # Members inherited from the mixin chain come first, then local ones.
    assert list(thing.members)[:3] == ["id", "tag", "created"]
    # Smithy serializes applies onto inherited members as separate entries.
    assert thing.members["id"].get_trait("documentation") == "Overridden doc."
    assert thing.members["tag"].get_trait("length") == {"min": 1}
    assert [str(k) for k in thing.members["id"].traits] == [
        "smithy.api#documentation",
        "smithy.api#required",
    ]
    # StampMixin's @internal is a local trait, so Thing does not inherit it.
    assert not thing.has_trait("internal")
    mixins = [str(s.id) for s in model.iter_shapes() if s.is_mixin]
    assert mixins == ["example.mini#IdMixin", "example.mini#StampMixin"]


def test_enum_members_target_unit(model: Model) -> None:
    color = model.expect_shape(_id("Color"), EnumShape)
    assert list(color.members) == ["RED", "GREEN", "BLUE"]
    red = color.members["RED"]
    assert red.target == ShapeId("smithy.api", "Unit")
    assert red.get_trait("enumValue") == "red"
