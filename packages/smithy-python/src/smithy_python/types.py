"""Generation of complete standalone types packages."""

from __future__ import annotations

import json
from collections.abc import Iterable

from . import dependencies as _dependencies
from . import generation as _generation
from . import models as _models
from . import schemas as _schemas

__all__ = ["TypesGenerator"]


class TypesGenerator:
    """Generate a standalone package containing schemas and lazy models."""

    def generate(
        self, context: _generation.GenerationContext[_generation.TypesSettings]
    ) -> None:
        """Register every file and dependency in the generation context."""
        _schemas.SchemaGenerator().generate(context)
        _models.ModelGenerator().generate(context)
        _write_package(context)


_GENERATED_COMMENT = "# Code generated by smithy-python-codegen DO NOT EDIT."
_GENERATED_MARKDOWN_COMMENT = (
    "<!-- Code generated by smithy-python-codegen DO NOT EDIT. -->"
)
_PYPROJECT_SUFFIX = """
[tool.pyright]
typeCheckingMode = "strict"
reportPrivateUsage = false
reportUnusedFunction = false
reportUnusedVariable = false
reportUnnecessaryComparison = false
reportUnusedClass = false
enableExperimentalFeatures = true
exclude = ["**/models.py"]

[tool.ruff]
target-version = "py312"

[tool.ruff.lint]
ignore = ["F841"]

[tool.ruff.format]
skip-magic-trailing-comma = true
"""


def _write_package(
    context: _generation.GenerationContext[_generation.TypesSettings],
) -> None:
    settings = context.settings
    package = settings.package
    directory = package.replace(".", "/")
    description = settings.package_description or f"{package} types package"

    context.dependencies.add(_dependencies.HATCHLING)
    context.files.text_file(
        "pyproject.toml",
        _render_pyproject(settings, context.dependencies, description),
    )
    context.files.text_file(
        "README.md",
        f"{_GENERATED_MARKDOWN_COMMENT}\n\n"
        f"## {package} Types Package\n\n{description}\n",
    )

    init = context.files.python_module(f"src/{directory}/__init__.py", package)
    init.line("__version__: str = ", repr(settings.package_version))
    context.files.python_module(
        f"src/{directory}/_private/__init__.py", f"{package}._private"
    )
    context.files.text_file(f"src/{directory}/py.typed", "")


def _render_pyproject(
    settings: _generation.TypesSettings,
    dependencies: _dependencies.DependencySet,
    description: str,
) -> str:
    package_root = settings.package.split(".", 1)[0]
    groups = "\n".join(
        f"{group} = {_toml_array(map(_requirement, values))}"
        for group in ("test", "docs")
        if (values := dependencies.for_group(group))
    )
    if groups:
        groups = f"\n\n[dependency-groups]\n{groups}"

    return f"""{_GENERATED_COMMENT}

[project]
name = {_toml_string(settings.package)}
version = {_toml_string(settings.package_version)}
description = {_toml_string(description)}
readme = "README.md"
requires-python = ">=3.12"
keywords = ["smithy", {_toml_string(settings.package)}]
license = {{text = "Apache-2.0"}}
dependencies = {_toml_array(map(_requirement, dependencies.for_group("runtime")))}{groups}

[build-system]
requires = {_toml_array(map(_requirement, dependencies.for_group("build")))}
build-backend = "hatchling.build"

[tool.hatch.build.targets.wheel]
packages = {_toml_array((f"src/{package_root}",))}

{_PYPROJECT_SUFFIX.lstrip()}"""


def _toml_array(values: Iterable[str]) -> str:
    items = tuple(values)
    return (
        "[\n" + "\n".join(f"    {_toml_string(value)}," for value in items) + "\n]"
        if items
        else "[]"
    )


def _requirement(dependency: _dependencies.Dependency) -> str:
    extras = f"[{','.join(dependency.extras)}]" if dependency.extras else ""
    return f"{dependency.package}{extras}{dependency.specifier}"


def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")
