"""Checks the documentation of the client generated from full-docs.smithy.

Usage: python3 full_docs_check.py <generated project directory>

The generated modules are parsed and compiled, and every check reads the decoded
docstrings, so the escaping of the source is checked too. A module that does not
compile is reported, and then no docs are read at all.

Once the docs are read from the source, both clients are imported, which needs the
runtime packages the generated client depends on. Importing a client defines its
operation methods, and each must then have the docs of its keyword overload.

A keyword overload takes its members as `**kwargs: Unpack[<input>Dict]`, so an
editor resolves each keyword's docs through the dictionary form's keys. The members
are documented there, and on the model's fields, in full; the operation's docs keep
their narrative, plugins and Returns, and do not repeat the members.
"""

import ast
import importlib
import inspect
import re
import sys
import warnings
from pathlib import Path, PurePosixPath

PACKAGE = Path(sys.argv[1]) / "src" / "docs_client"
FAILURES = []

# The documented members of AssumeAccessInput, by parameter name, in model order.
DOCUMENTED = ["duration_seconds", "plugins_", "tag", "source", "mode"]
# Its idempotency token is its last member. The model does not document it, so the
# note that the client fills it is all of its docs, once, wherever it is documented.
TOKEN = "client_token"
TOKEN_DOCS = "This field is autopopulated if not provided."
NARRATIVE = (
    "Returns temporary access for a session.\n\n"
    "Access is revoked when the session ends.\n"
)
DURATION_LEAD = (
    "The duration of the session, in seconds. A session costs $5 per hour and its "
    "duration can range from 900 seconds up to the maximum that is set for the role."
)
TAG_KEY = (
    "The key of the tag. Keys are case sensitive.\n\n"
    "Keys that start with `aws:` are reserved."
)
PLUGINS = (
    "A list of callables that modify the configuration dynamically. Changes made by "
    "these plugins only apply for the duration of the operation execution and will "
    "not affect any other operation invocations."
)
# What MigrateSession's docs decode to. A backslash is a backslash, wherever it is and
# whatever follows it, and a dollar sign is one dollar sign.
MIGRATE_NARRATIVE = (
    "Migrates a session to another host, which costs $5 for each `$LATEST` version. "
    "During migration, the original `D:\\Users\\%USERNAME%` user profile folder is "
    "renamed to `D:\\Users\\%USERNAME%MMddyyTHHmmss%.NotMigrated`. A new "
    "`D:\\Users\\%USERNAME%\\` folder is generated by the new OS."
)
ADMIN_LEAD = (
    "The user or group that administers the migrated session. Acceptable formats "
    "include: `DOMAIN\\User1`, `user@domain`, `@group1`, and `@DOMAIN\\group1`."
)
MODE = "- `fast` skips the audit trail. - `safe` records every call."

# The dictionary form each operation's keyword overload unpacks. A sync client
# unpacks the plain form of an input with a streaming body; the async client unpacks
# the form whose body may also be an async stream.
SYNC_KEYWORDS = {
    "assume_access": "_models.AssumeAccessInputDict",
    "migrate_session": "_models.MigrateSessionInputDict",
    "overload": "_models.OverloadInputDict",
    "upload_document": "_models.UploadDocumentInputDict",
}
ASYNC_KEYWORDS = {
    **SYNC_KEYWORDS,
    "upload_document": "_models.AsyncUploadDocumentInputDict",
    "watch_access": "_models.WatchAccessInputDict",
}


def check(condition, message):
    if not condition:
        FAILURES.append(message)


def equal(actual, expected, what):
    message = "%s:\n  expected %r\n  actual   %r" % (what, expected, actual)
    check(actual == expected, message)


def load(name):
    path = PACKAGE / name
    source = path.read_text(encoding="utf-8")
    try:
        with warnings.catch_warnings():
            # An invalid escape sequence in a docstring is only a warning.
            warnings.simplefilter("error")
            tree = ast.parse(source, str(path))
            if path.suffix == ".py":
                compile(source, str(path), "exec")
    except SyntaxError as error:
        FAILURES.append("%s does not compile: %s" % (name, error))
        return None
    return tree


def flat(text):
    return " ".join(text.split())


def classes(tree):
    return {node.name: node for node in tree.body if isinstance(node, ast.ClassDef)}


def stub_classes(name, seen):
    """Maps each class a stub exposes to its declaration, wherever that is.

    The stub of a large client declares no models itself: it re-exports them from
    partition stubs. Relative imports of other stubs are followed, so that the docs
    are read from the declarations. A partition that does not parse is reported.
    """
    if name in seen:
        return {}
    seen.add(name)
    tree = load(name)
    if tree is None:
        return {}
    found = {}
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            found[node.name] = node
        elif isinstance(node, ast.ImportFrom) and node.level and node.module:
            directory = PurePosixPath(name).parent
            for _ in range(node.level - 1):
                directory = directory.parent
            imported = directory.joinpath(*node.module.split(".")).with_suffix(".pyi")
            if not (PACKAGE / imported).is_file():
                continue
            exposed = stub_classes(str(imported), seen)
            for alias in node.names:
                if alias.name == "*":
                    found.update(exposed)
                elif alias.name in exposed:
                    found[alias.asname or alias.name] = exposed[alias.name]
    return found


def fields(cls):
    """Maps each annotated field to its annotation and the docstring after it."""
    found = {}
    for node, after in zip(cls.body, cls.body[1:] + [None]):
        if not isinstance(node, ast.AnnAssign):
            continue
        doc = None
        if isinstance(after, ast.Expr):
            value = getattr(after.value, "value", None)
            if isinstance(value, str):
                doc = inspect.cleandoc(value)
        found[node.target.id] = (ast.unparse(node.annotation), doc)
    return found


def is_overload(node):
    for decorator in node.decorator_list:
        if isinstance(decorator, ast.Attribute):
            name = decorator.attr
        else:
            name = getattr(decorator, "id", "")
        if name.endswith("overload"):
            return True
    return False


def names(arguments):
    return [argument.arg for argument in arguments]


def unpacked(annotation, tree):
    """Returns the type an annotation unpacks, or None if it is not Unpack[...].

    Unpack is recognized by what the module imports, whatever name it is bound to.
    """
    if isinstance(annotation, ast.Constant) and isinstance(annotation.value, str):
        annotation = ast.parse(annotation.value, mode="eval").body
    if not isinstance(annotation, ast.Subscript):
        return None
    direct, modules = set(), set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and not node.level:
            if node.module in ("typing", "typing_extensions"):
                for alias in node.names:
                    if alias.name == "Unpack":
                        direct.add(alias.asname or alias.name)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name in ("typing", "typing_extensions"):
                    modules.add(alias.asname or alias.name)
    value = annotation.value
    if isinstance(value, ast.Name) and value.id in direct:
        return ast.unparse(annotation.slice)
    if (
        isinstance(value, ast.Attribute)
        and value.attr == "Unpack"
        and isinstance(value.value, ast.Name)
        and value.value.id in modules
    ):
        return ast.unparse(annotation.slice)
    return None


def plugins_type(node):
    for argument in node.args.kwonlyargs:
        if argument.arg == "plugins":
            return ast.unparse(argument.annotation)
    return None


def methods(tree, client):
    """Reads each operation method of a client from its definitions.

    A method is two overloads and an implementation, in that order. The first
    overload takes the whole request, positionally; the second takes its members as
    keyword arguments, `**kwargs: Unpack[...]` of the request's dictionary form, and
    is the only one with docs. The implementation takes either.

    Returns the type each method's keyword overload unpacks and its docs, which are
    the keyword overload's, and the type of the request the first overload takes.
    """
    definitions = {}
    for node in classes(tree)[client].body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if node.name.startswith("_"):
            continue
        definitions.setdefault(node.name, []).append(node)
    found, requests = {}, {}
    for name, nodes in definitions.items():
        what = "%s %s" % (client, name)
        if [is_overload(node) for node in nodes] != [True, True, False]:
            FAILURES.append(what + " is not two overloads and an implementation")
            continue
        whole, keyword, implementation = nodes

        equal(names(whole.args.posonlyargs), ["self", "request"], what + " request")
        equal(names(whole.args.kwonlyargs), ["plugins"], what + " request keywords")
        equal(ast.get_docstring(whole), None, what + " request overload docs")
        requests[name] = ast.unparse(whole.args.posonlyargs[1].annotation)

        equal(names(keyword.args.posonlyargs), ["self"], what + " keyword overload")
        check(not keyword.args.args, what + " keyword overload positional parameters")
        check(not keyword.args.vararg, what + " keyword overload *args")
        # The members are not spelled out one by one: plugins is the only keyword of
        # the method's own, and the members are the keys of the unpacked form.
        equal(
            names(keyword.args.kwonlyargs),
            ["plugins"],
            what + " keyword overload keywords",
        )
        equal(
            plugins_type(keyword),
            plugins_type(whole),
            what + " keyword overload plugins type",
        )
        equal(
            [default and ast.unparse(default) for default in keyword.args.kw_defaults],
            ["None"],
            what + " keyword overload plugins default",
        )
        target = None
        kwarg = keyword.args.kwarg
        if kwarg is None:
            FAILURES.append(what + " keyword overload has no **kwargs")
        else:
            equal(kwarg.arg, "kwargs", what + " keyword overload **kwargs name")
            target = unpacked(kwarg.annotation, tree)
            check(
                target is not None,
                "%s keyword overload **kwargs is not Unpack[...]: %r"
                % (what, kwarg.annotation and ast.unparse(kwarg.annotation)),
            )

        # Its docs are the keyword overload's, given to it at runtime, not repeated.
        equal(ast.get_docstring(implementation), None, what + " implementation docs")
        equal(
            (
                names(implementation.args.posonlyargs),
                getattr(implementation.args.vararg, "arg", None),
                names(implementation.args.kwonlyargs),
                getattr(implementation.args.kwarg, "arg", None),
            ),
            (["self"], "args", ["plugins"], "kwargs"),
            what + " implementation parameters",
        )

        found[name] = (target, ast.get_docstring(keyword))
    return found, requests


def sections(doc):
    """Splits an operation docstring into its narrative, Args entries and Returns."""
    lines = doc.split("\n")
    args, returns = lines.index("Args:"), lines.index("Returns:")
    entries = {}
    current = None
    for line in lines[args + 1 : returns]:
        match = re.match(r"    (\w+):(?: (.*))?$", line)
        if match:
            current = match.group(1)
            entries[current] = [match.group(2) or ""]
        else:
            # Everything else belongs to the entry above it, so it is indented past
            # the entry's name.
            inside = not line or line.startswith("        ")
            check(inside, "not inside an Args entry: %r" % line)
            entries[current].append(line)
    for body in entries.values():
        while body and not body[-1]:
            body.pop()
    narrative = "\n".join(lines[:args])
    returned = flat(" ".join(lines[returns + 1 :]))
    return narrative, Entries(entries), returned


class Entries(dict):
    def __missing__(self, name):
        return ["<no Args entry>"]


def check_operations(models, sync, aio):
    # Sync clients have no event streams; everything else is documented alike.
    equal(
        sorted(sync),
        ["assume_access", "migrate_session", "overload", "upload_document"],
        "sync operations",
    )
    equal(
        sorted(aio),
        [
            "assume_access",
            "migrate_session",
            "overload",
            "upload_document",
            "watch_access",
        ],
        "async operations",
    )
    for name in sync:
        equal(sync[name][1], aio[name][1], "sync and async docs of " + name)

    # Each keyword overload unpacks its input's dictionary form, named exactly. Only
    # the async client unpacks the form whose body may be an async stream.
    for label, client, expected in (
        ("sync", sync, SYNC_KEYWORDS),
        ("async", aio, ASYNC_KEYWORDS),
    ):
        equal(
            {name: target for name, (target, _) in client.items()},
            expected,
            label + " keyword overload Unpack targets",
        )
    check(
        sync["upload_document"][0] != aio["upload_document"][0],
        "sync and async upload_document unpack the same form",
    )

    for label, client in (("sync", sync), ("async", aio)):
        for name, (target, doc) in client.items():
            what = "%s %s" % (label, name)
            _, entries, _ = sections(doc)

            # The operation's Args document only its own plugins parameter, in full.
            equal(list(entries), ["plugins"], what + " Args entries")
            equal(entries["plugins"][0], "", what + " plugins first line")
            equal(flat(" ".join(entries["plugins"])), PLUGINS, what + " plugins docs")

            # The members are documented on the keys of the unpacked form, which is
            # where an editor finds them, so the operation does not repeat them.
            params = (target or "").removeprefix("_models.")
            if params not in models:
                FAILURES.append("%s unpacks an undeclared form: %r" % (what, target))
                continue
            for key, (_, docs) in fields(models[params]).items():
                if docs:
                    check(
                        flat(docs) not in flat(doc),
                        "%s docs repeat the docs of %s.%s" % (what, params, key),
                    )

        narrative, _, returns = sections(client["assume_access"][1])
        equal(narrative[: len(NARRATIVE)], NARRATIVE, label + " operation narrative")
        equal(returns, "An instance of `AssumeAccessOutput`.", label + " Returns")
        _, _, returns = sections(client["overload"][1])
        equal(returns, "An instance of `OverloadOutput`.", label + " overload Returns")

    # The initial request of an event stream operation is unpacked too; its events
    # are sent through the stream, so they are not a key of its form.
    _, _, returns = sections(aio["watch_access"][1])
    equal(
        returns,
        "An `AsyncInputEventStream` for client-to-server streaming.",
        "watch_access Returns",
    )


def check_literals(models, sync, aio):
    # Windows paths and account names decode to what the model says in the model's
    # docs, on the dictionary form's key, and in the operation's own narrative, which
    # is also where a dollar sign is easiest to double.
    admin = fields(models["MigrateSessionInput"])["admin"][1]
    equal(flat(admin)[: len(ADMIN_LEAD)], ADMIN_LEAD, "model admin docs")
    check(
        "\n\nWarning:\n    Use this option very carefully, because" in admin,
        "model admin docs lack the warning: %r" % admin,
    )
    check(
        "regardless of its permissions." in flat(admin),
        "model admin docs lack the end of the warning: %r" % admin,
    )
    equal(
        fields(models["MigrateSessionInputDict"])["admin"][1],
        admin,
        "MigrateSessionInputDict.admin docs",
    )
    for label, client in (("sync", sync), ("async", aio)):
        narrative, _, _ = sections(client["migrate_session"][1])
        equal(
            flat(narrative)[: len(MIGRATE_NARRATIVE)],
            MIGRATE_NARRATIVE,
            label + " migrate_session narrative",
        )


def check_params(models):
    # Model docs are as they were, and decode to what the model says.
    equal(
        ast.get_docstring(models["SessionTag"]),
        "A key and value attached to a session.",
        "SessionTag docs",
    )
    equal(
        ast.get_docstring(models["CredentialSourceWebToken"]),
        "A web identity token issued by the provider.",
        "CredentialSourceWebToken docs",
    )
    duration = fields(models["AssumeAccessInput"])["duration_seconds"][1]
    for expected in (
        "costs $5 per hour",
        "\n\nWarning:\n    Never share the session with an untrusted party.",
        "\n\n- Compute the default as 2 * 3 * 600 seconds.\n",
        '- Quote the unit as `"""seconds"""` in `C:\\dir\\session.ini`.',
    ):
        message = "model duration_seconds docs lack %r: %r" % (expected, duration)
        check(expected in duration, message)
    check(
        "Chained sessions are limited to one hour." in flat(duration),
        "model duration_seconds docs lack the end of the warning: %r" % duration,
    )

    # A dictionary form says what it is; it does not repeat the operation's docs.
    equal(
        ast.get_docstring(models["AssumeAccessInputDict"]),
        "Dictionary form of `AssumeAccessInput`.",
        "AssumeAccessInputDict docs",
    )

    # Each key is documented exactly as the model's field is, and typed as before.
    for params, model in (
        ("AssumeAccessInputDict", "AssumeAccessInput"),
        ("MigrateSessionInputDict", "MigrateSessionInput"),
        ("SessionTagDict", "SessionTag"),
        ("UploadDocumentInputDict", "UploadDocumentInput"),
        ("AsyncUploadDocumentInputDict", "UploadDocumentInput"),
        ("WatchAccessInputDict", "WatchAccessInput"),
        ("OverloadInputDict", "OverloadInput"),
    ):
        keys, attributes = fields(models[params]), fields(models[model])
        equal(list(keys), list(attributes), params + " keys")
        for key in keys:
            equal(keys[key][1], attributes[key][1], "%s.%s docs" % (params, key))

    # The full prose of every member, which the operations no longer repeat, is on
    # the model's field and on the dictionary form's key alike.
    for model, params, key, expected in (
        (
            "AssumeAccessInput",
            "AssumeAccessInputDict",
            "plugins_",
            "The names of the plugins to enable for the session.",
        ),
        (
            "AssumeAccessInput",
            "AssumeAccessInputDict",
            "tag",
            "A tag to attach to the session.",
        ),
        (
            "AssumeAccessInput",
            "AssumeAccessInputDict",
            "source",
            "Where the caller's credentials come from.",
        ),
        ("AssumeAccessInput", "AssumeAccessInputDict", TOKEN, TOKEN_DOCS),
        (
            "OverloadInput",
            "OverloadInputDict",
            "input",
            "The text to check, which is not the request itself.",
        ),
        (
            "OverloadInput",
            "OverloadInputDict",
            "tag",
            "A tag to check the text against.",
        ),
        (
            "UploadDocumentInput",
            "UploadDocumentInputDict",
            "name",
            "The name of the document.",
        ),
        (
            "UploadDocumentInput",
            "AsyncUploadDocumentInputDict",
            "name",
            "The name of the document.",
        ),
        (
            "UploadDocumentInput",
            "UploadDocumentInputDict",
            "body",
            "The bytes of the document.",
        ),
        (
            "WatchAccessInput",
            "WatchAccessInputDict",
            "session_id",
            "The session to watch.",
        ),
    ):
        for owner in (model, params):
            documented = fields(models[owner]).get(key, (None, None))[1]
            equal(documented, expected, "%s.%s docs" % (owner, key))

    # A member's docs that open with a list keep each item on its own line.
    for owner in ("AssumeAccessInput", "AssumeAccessInputDict"):
        mode = fields(models[owner])["mode"][1] or ""
        equal(flat(mode), MODE, owner + ".mode docs")
        check(
            "\n- `safe` records every call." in mode,
            "%s.mode docs lose the list: %r" % (owner, mode),
        )
        duration = fields(models[owner])["duration_seconds"][1] or ""
        equal(
            flat(duration)[: len(DURATION_LEAD)],
            DURATION_LEAD,
            owner + ".duration_seconds lead",
        )

    overload_keys = fields(models["OverloadInputDict"])
    equal(list(overload_keys), ["input", "tag"], "OverloadInputDict keys")
    equal(overload_keys["input"][0], "str | None", "OverloadInputDict.input type")
    keys = fields(models["AssumeAccessInputDict"])
    equal(
        list(keys),
        [*DOCUMENTED, "undocumented", TOKEN],
        "AssumeAccessInputDict keys",
    )
    equal(keys["duration_seconds"][0], "Required[int]", "duration_seconds key type")
    equal(keys["tag"][0], "SessionTag | SessionTagDict | None", "tag key type")
    equal(
        keys["plugins_"][1],
        "The names of the plugins to enable for the session.",
        "plugins_ key docs",
    )
    equal(keys["undocumented"], ("str | None", None), "undocumented key")
    # The token's note is on the model's field and on the key, and nowhere twice.
    equal(
        fields(models["AssumeAccessInput"])[TOKEN],
        ("str | None", TOKEN_DOCS),
        "model client_token",
    )
    equal(keys[TOKEN], ("str | None", TOKEN_DOCS), "client_token key")
    equal(
        fields(models["SessionTagDict"])["key"],
        ("Required[str]", TAG_KEY),
        "SessionTagDict.key",
    )
    equal(
        list(fields(models["WatchAccessInputDict"])),
        ["session_id"],
        "WatchAccessInputDict keys",
    )
    equal(
        fields(models["UploadDocumentInputDict"])["body"],
        ("Required[SyncStreamingBlob]", "The bytes of the document."),
        "UploadDocumentInputDict.body",
    )
    equal(
        fields(models["AsyncUploadDocumentInputDict"])["body"],
        ("Required[StreamingBlob]", "The bytes of the document."),
        "AsyncUploadDocumentInputDict.body",
    )

    # The single key of a union alternative carries its own variant's docs.
    equal(
        fields(models["CredentialSourceWebTokenDict"]),
        {"web_token": ("str", "A web identity token issued by the provider.")},
        "CredentialSourceWebTokenDict",
    )
    equal(
        fields(models["CredentialSourceProfileDict"]),
        {
            "profile": (
                "SessionTag | SessionTagDict",
                "A stored profile to read credentials from.",
            ),
        },
        "CredentialSourceProfileDict",
    )


def check_requests(sync, aio):
    # The whole request is the input model or its dictionary form. Only the async
    # client takes the form whose body may be an async stream.
    for label, client, expected in (
        ("sync", sync, {}),
        (
            "async",
            aio,
            {
                "upload_document": "_models.UploadDocumentInput"
                " | _models.UploadDocumentInputDict"
                " | _models.AsyncUploadDocumentInputDict",
                "watch_access": "_models.WatchAccessInput"
                " | _models.WatchAccessInputDict",
            },
        ),
    ):
        for name in ("assume_access", "overload", "upload_document", "watch_access"):
            if name not in client:
                continue
            shape = "".join(part.title() for part in name.split("_"))
            plain = "_models.%sInput | _models.%sInputDict" % (shape, shape)
            equal(
                client[name],
                expected.get(name, plain),
                "%s %s request type" % (label, name),
            )


def check_runtime(sync, aio):
    # Importing a client runs its class body, which defines every overload, so a
    # method named like a name the class body uses breaks it.
    sys.path.insert(0, str(PACKAGE.parent))
    for label, module, client, documented in (
        ("sync", "docs_client.client", "DocsService", sync),
        ("async", "docs_client.aio.client", "AsyncDocsService", aio),
    ):
        try:
            cls = getattr(importlib.import_module(module), client)
        except Exception as error:
            FAILURES.append("%s cannot be imported: %r" % (module, error))
            continue
        # Each implementation has its keyword overload's docs, for help().
        for name, (_, doc) in documented.items():
            runtime = getattr(cls, name).__doc__
            equal(
                runtime and inspect.cleandoc(runtime),
                doc,
                "%s %s runtime docs" % (label, name),
            )


def main():
    # The stub is read through its re-exports, so every partition stub is tried too.
    # models.py is not read, but it has the same member docs and is what is imported.
    models = stub_classes("models.pyi", set())
    trees = [load(name) for name in ("client.py", "aio/client.py", "models.py")]
    # Docs can only be read from modules that compile, so every module is tried first.
    if not FAILURES:
        # The models and their dictionary forms are read from the stubs alone, so
        # they are checked whatever shape the operation methods have.
        check_params(models)
        before = len(FAILURES)
        sync, sync_requests = methods(trees[0], "DocsService")
        aio, aio_requests = methods(trees[1], "AsyncDocsService")
        # Every method must have been read before its docs can be checked.
        if len(FAILURES) == before:
            check_operations(models, sync, aio)
            check_literals(models, sync, aio)
            check_requests(sync_requests, aio_requests)
            check_runtime(sync, aio)
    if FAILURES:
        print("%d documentation checks failed:\n" % len(FAILURES))
        print("\n\n".join(FAILURES))
        sys.exit(1)
    print("documentation checks passed")


if __name__ == "__main__":
    main()
