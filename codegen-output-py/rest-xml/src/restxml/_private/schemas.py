_PARTITIONS = {
    name: index for index, names in enumerate(_PARTITION_NAMES) for name in names
}
del _PARTITION_NAMES


def __getattr__(name: str):
    try:
        partition = _PARTITIONS[name]
    except KeyError as error:
        raise AttributeError(name) from error
    module = import_module(f".schemas_{partition:01d}", __package__)
    value = getattr(module, name)
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    return sorted({*globals(), *_PARTITIONS})
